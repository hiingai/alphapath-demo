const PORT = 9222;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const l = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const p = l.find((t) => t.type === 'page');
const ws = new WebSocket(p.webSocketDebuggerUrl);
let id = 0; const pd = new Map();
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pd.has(m.id)) { const q = pd.get(m.id); pd.delete(m.id); m.error ? q.rej(new Error(JSON.stringify(m.error))) : q.res(m.result); } });
await new Promise((r, j) => { ws.addEventListener('open', r); ws.addEventListener('error', j); });
const send = (m, pr = {}) => { const i = ++id; ws.send(JSON.stringify({ id: i, method: m, params: pr })); return new Promise((res, rej) => pd.set(i, { res, rej })); };
const ev = async (x) => (await send('Runtime.evaluate', { expression: x, returnByValue: true })).result.value;
await send('Runtime.enable');
const before = await ev(`(()=>{const s=document.querySelector('.proc .step'); return s? getComputedStyle(s).display : 'none-step';})()`);
await ev(`document.querySelector('.prochead').click()`);
await sleep(300);
const after = await ev(`(()=>{const s=document.querySelector('.proc .step'); return s? getComputedStyle(s).display : 'none-step';})()`);
const label = await ev(`document.querySelector('.prochead .pt').textContent`);
const ansVisible = await ev(`(()=>{const a=document.querySelector('.bubble .ans'); return a? getComputedStyle(a).display+' | '+a.innerText.slice(0,24) : 'no-ans';})()`);
console.log('step display before/after fold:', before, '->', after);
console.log('header label after fold:', label);
console.log('answer still visible:', ansVisible);
ws.close(); process.exit(0);
